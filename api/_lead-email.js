/**
 * HOT LEAD email for the demo agent.
 *
 * The prompt says: "Never claim the email was successfully sent unless the
 * email tool confirms successful delivery or submission." So this module
 * returns an honest { ok, detail } and never pretends. If it is not
 * configured, it says so, and the agent tells the visitor the truth.
 *
 * Provider: Brevo transactional email (the owner's chosen provider).
 *
 * Environment variables:
 *   BREVO_API_KEY     required to send at all
 *   LEAD_EMAIL_FROM   required. Must be a sender Brevo has verified.
 *   LEAD_EMAIL_NAME   optional, defaults to "Conversing AI Demo"
 *   LEAD_EMAIL_BCC    optional. Copies every demo lead to your own inbox.
 */

const BREVO_ENDPOINT = 'https://api.brevo.com/v3/smtp/email';

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** Strip everything but digits so wa.me gets a clean number. */
function waDigits(n) {
  return String(n || '').replace(/[^\d]/g, '');
}

function block(title, body) {
  if (!body) return '';
  return `
    <tr><td style="padding:18px 24px 0;">
      <h2 style="margin:0 0 8px;font:700 15px/1.3 Arial,Helvetica,sans-serif;color:#0f172a;">${esc(title)}</h2>
      <div style="font:400 14px/1.7 Arial,Helvetica,sans-serif;color:#334155;white-space:pre-wrap;">${esc(body)}</div>
    </td></tr>`;
}

function buildHtml(d) {
  const wa = waDigits(d.whatsapp);
  const waBtn = wa
    ? `<a href="https://wa.me/${wa}" style="display:inline-block;background:#25d366;color:#052e16;font:700 14px/1 Arial,Helvetica,sans-serif;padding:13px 22px;border-radius:7px;text-decoration:none;">Chat with Lead on WhatsApp</a>`
    : `<span style="font:400 13px/1.6 Arial,Helvetica,sans-serif;color:#64748b;">No WhatsApp number was supplied.</span>`;

  const row = (label, value) => value
    ? `<tr>
         <td style="padding:5px 0;font:700 13px/1.5 Arial,Helvetica,sans-serif;color:#64748b;width:110px;vertical-align:top;">${esc(label)}</td>
         <td style="padding:5px 0;font:400 14px/1.5 Arial,Helvetica,sans-serif;color:#0f172a;">${esc(value)}</td>
       </tr>`
    : '';

  return `<!doctype html>
<html><body style="margin:0;padding:24px 12px;background:#f1f5f9;">
<table role="presentation" cellpadding="0" cellspacing="0" style="max-width:620px;margin:0 auto;background:#ffffff;border-radius:12px;overflow:hidden;border:1px solid #e2e8f0;">

  <tr><td style="background:linear-gradient(135deg,#1d4ed8,#2563eb);padding:22px 24px;">
    <p style="margin:0;font:800 12px/1 Arial,Helvetica,sans-serif;letter-spacing:.14em;color:#bfdbfe;">CONVERSING AI</p>
    <h1 style="margin:7px 0 0;font:800 23px/1.25 Arial,Helvetica,sans-serif;color:#ffffff;">HOT LEAD</h1>
    <p style="margin:5px 0 0;font:400 13px/1.5 Arial,Helvetica,sans-serif;color:#dbeafe;">New website visitor enquiry</p>
  </td></tr>

  <tr><td style="padding:20px 24px 0;">
    <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
      ${row('Website', d.website)}
      ${row('Visitor', d.name)}
      ${row('Email', d.email)}
      ${row('Phone', d.phone)}
      ${row('WhatsApp', d.whatsapp)}
    </table>
  </td></tr>

  ${block('Visitor Enquiry', d.enquiry)}
  ${block('AI Agent Responses', d.responses)}
  ${block('Conversation History', d.conversation)}
  ${block('Recommended Action', d.recommended_action)}

  <tr><td style="padding:22px 24px 8px;">${waBtn}</td></tr>

  ${d.phone ? `<tr><td style="padding:4px 24px 22px;">
    <p style="margin:0;font:400 14px/1.6 Arial,Helvetica,sans-serif;color:#334155;">
      Or call directly: <a href="tel:${esc(String(d.phone).replace(/\s/g, ''))}" style="color:#1d4ed8;font-weight:700;text-decoration:none;">${esc(d.phone)}</a>
    </p></td></tr>` : ''}

  <tr><td style="padding:16px 24px 22px;border-top:1px solid #e2e8f0;">
    <p style="margin:0;font:400 12px/1.6 Arial,Helvetica,sans-serif;color:#94a3b8;">
      This is what your business would receive when a visitor becomes a potential customer.
      Generated by the Conversing AI demo agent at conversingai.com.
    </p>
  </td></tr>

</table>
</body></html>`;
}

/**
 * Sends the lead email.
 * @returns {Promise<{ok: boolean, detail: string}>} never throws
 */
export async function sendLeadEmail(d) {
  const key = process.env.BREVO_API_KEY;
  const from = process.env.LEAD_EMAIL_FROM;

  if (!key || !from) {
    return {
      ok: false,
      detail:
        'Email sending is not configured on this deployment (BREVO_API_KEY and/or LEAD_EMAIL_FROM are missing). ' +
        'Tell the visitor honestly that the lead email could not be sent, and do not claim it was.',
    };
  }
  if (!d || !d.email) {
    return { ok: false, detail: 'No recipient email address was supplied, so nothing was sent.' };
  }

  const payload = {
    sender: { email: from, name: process.env.LEAD_EMAIL_NAME || 'Conversing AI Demo' },
    to: [{ email: d.email, name: d.name || undefined }],
    subject: `HOT LEAD: New Website Visitor Enquiry – ${d.website || 'your website'}`,
    htmlContent: buildHtml(d),
  };
  if (process.env.LEAD_EMAIL_BCC) {
    payload.bcc = [{ email: process.env.LEAD_EMAIL_BCC }];
  }

  try {
    const ctrl = new AbortController();
    const t = setTimeout(() => ctrl.abort(), 12_000);

    const res = await fetch(BREVO_ENDPOINT, {
      method: 'POST',
      headers: {
        'api-key': key,
        'content-type': 'application/json',
        accept: 'application/json',
      },
      body: JSON.stringify(payload),
      signal: ctrl.signal,
    });
    clearTimeout(t);

    if (res.ok) {
      let id = '';
      try { id = (await res.json())?.messageId || ''; } catch { /* body is optional */ }
      return {
        ok: true,
        detail: `Email accepted for delivery to ${d.email}${id ? ` (message id ${id})` : ''}.`,
      };
    }

    let body = '';
    try { body = (await res.text()).slice(0, 180); } catch { /* ignore */ }
    console.error('lead email failed:', res.status, body);
    return {
      ok: false,
      detail: `The email provider rejected the send (HTTP ${res.status}). The email was NOT delivered. Tell the visitor honestly.`,
    };
  } catch (err) {
    console.error('lead email error:', err?.name, err?.message);
    return {
      ok: false,
      detail:
        err?.name === 'AbortError'
          ? 'The email provider timed out. The email was NOT confirmed as sent. Tell the visitor honestly.'
          : 'The email could not be sent because of a network error. Tell the visitor honestly.',
    };
  }
}
