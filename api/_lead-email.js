/** Plain-text alternative. Mail without one looks more like spam. */
function buildText(d) {
  const lines = [
    'HOT LEAD — New website visitor enquiry',
    '',
    `Website:  ${d.website || '-'}`,
    `Visitor:  ${d.name || '-'}`,
    `Email:    ${d.email || '-'}`,
    `Phone:    ${d.phone || '-'}`,
    `WhatsApp: ${d.whatsapp || '-'}`,
  ];
  const add = (t, b) => { if (b) lines.push('', t.toUpperCase(), String(b)); };
  add('Visitor enquiry', d.enquiry);
  add('AI agent responses', d.responses);
  add('Conversation history', d.conversation);
  add('Recommended action', d.recommended_action);
  const wa = waDigits(d.whatsapp);
  if (wa) lines.push('', `Chat on WhatsApp: https://wa.me/${wa}`);
  lines.push('', 'Generated by the Conversing AI demo agent at conversingai.com.');
  return lines.join('\n');
}

let cachedTransport = null;

/* Send-once guard. A visitor should never receive the same lead twice if the
 * model calls the tool more than once in a conversation. Keyed by recipient
 * plus website, held briefly in memory. Serverless instances are ephemeral so
 * this is not a hard guarantee, but it catches the realistic case: repeat
 * calls within the same short-lived conversation on the same instance. */
const recentlySent = new Map();
const DEDUPE_WINDOW_MS = 10 * 60 * 1000;

function dedupeKey(d) {
  return String(d.email || '').toLowerCase() + '|' + String(d.website || '').toLowerCase();
}

function alreadySent(d) {
  const key = dedupeKey(d);
  const at = recentlySent.get(key);
  if (at && Date.now() - at < DEDUPE_WINDOW_MS) return true;
  for (const [k, t] of recentlySent) {
    if (Date.now() - t > DEDUPE_WINDOW_MS) recentlySent.delete(k);
  }
  return false;
}

function transport() {
  if (cachedTransport) return cachedTransport;
  const port = Number(process.env.SMTP_PORT || 465);
  const host = process.env.SMTP_HOST;

  /* Shared cPanel servers present a wildcard certificate for the HOSTING
   * provider (*.web-hosting.com), not for the customer's own mail subdomain.
   * Connecting to mail.conversingai.com therefore fails strict TLS checks
   * with ERR_TLS_CERT_ALTNAME_INVALID, which nodemailer surfaces as a
   * connection failure rather than a clear certificate error.
   *
   * The fix is to connect to the server's real hostname, which the
   * certificate does cover, and leave verification ON. Both names resolve to
   * the same machine, so mail still leaves from the same server and stays
   * SPF- and DKIM-aligned. SMTP_SERVERNAME lets that be set without changing
   * the From address.
   *
   * Turning rejectUnauthorized off would also "work", but it would disable
   * certificate checking on the path carrying the mailbox password. */
  const servername = process.env.SMTP_SERVERNAME || host;

  cachedTransport = nodemailer.createTransport({
    host,
    port,
    secure: port === 465,            // 465 is implicit TLS; 587 upgrades via STARTTLS
    auth: { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS },
    tls: { servername, minVersion: 'TLSv1.2' },
    connectionTimeout: 10_000,
    greetingTimeout: 8_000,
    socketTimeout: 20_000,
    pool: false,                      // serverless: one connection, then done
  });
  return cachedTransport;
}

/**
 * Sends the lead email through the project's cPanel mailbox.
 * @returns {Promise<{ok: boolean, detail: string}>} never throws
 */
export async function sendLeadEmail(d) {
  const { SMTP_HOST, SMTP_USER, SMTP_PASS } = process.env;

  if (!SMTP_HOST || !SMTP_USER || !SMTP_PASS) {
    return {
      ok: false,
      detail:
        'Email sending is not configured on this deployment (SMTP_HOST, SMTP_USER or SMTP_PASS is missing). ' +
        'Tell the visitor honestly that the lead email could not be sent, and do not claim it was.',
    };
  }
  if (!d || !d.email) {
    return { ok: false, detail: 'No recipient email address was supplied, so nothing was sent.' };
  }

  if (alreadySent(d)) {
    return {
      ok: true,
      detail: `The lead email for ${d.email} was already sent a moment ago, so it was not sent again. ` +
        'Tell the visitor it is on its way; do not send another.',
    };
  }

  const from = process.env.LEAD_EMAIL_FROM || SMTP_USER;
  const name = process.env.LEAD_EMAIL_NAME || 'Conversing AI Demo';

  /* If the Bcc is the same mailbox as the recipient, drop it. Otherwise one
   * send lands twice in the same inbox, which looks like the agent emailed
   * the visitor twice and undermines trust in the demo. */
  const bccRaw = (process.env.LEAD_EMAIL_BCC || '').trim();
  const bcc = bccRaw && bccRaw.toLowerCase() !== String(d.email).trim().toLowerCase()
    ? bccRaw
    : undefined;

  try {
    const info = await transport().sendMail({
      from: `"${name}" <${from}>`,
      to: d.email,
      bcc,
      replyTo: bccRaw || from,
      subject: `HOT LEAD: New Website Visitor Enquiry – ${d.website || 'your website'}`,
      text: buildText(d),
      html: buildHtml(d),
    });

    // nodemailer reports which recipients the server accepted. If ours is
    // not among them, the send did not actually succeed.
    const accepted = Array.isArray(info?.accepted) ? info.accepted : [];
    if (!accepted.length) {
      return {
        ok: false,
        detail: 'The mail server did not accept the recipient. The email was NOT delivered. Tell the visitor honestly.',
      };
    }

    recentlySent.set(dedupeKey(d), Date.now());
    return {
      ok: true,
      detail: `Email accepted by the mail server for delivery to ${accepted.join(', ')}` +
        (info.messageId ? ` (message id ${info.messageId})` : '') + '.',
    };
  } catch (err) {
    console.error('lead email failed:', err?.code, err?.message);

    let detail = 'The email could not be sent because of a mail server error. Tell the visitor honestly.';
    if (err?.code === 'EAUTH') {
      detail = 'The mailbox credentials were rejected. The email was NOT sent. Tell the visitor honestly.';
    } else if (err?.code === 'ETIMEDOUT' || err?.code === 'ECONNECTION' || err?.code === 'ESOCKET') {
      detail = 'The mail server could not be reached in time. The email was NOT confirmed as sent. Tell the visitor honestly.';
    } else if (/ALTNAME|CERT|self.signed|unable to verify/i.test(err?.code + ' ' + err?.message)) {
      detail = 'The mail server TLS certificate did not match the hostname, so the connection was refused. ' +
        'The email was NOT sent. Tell the visitor honestly.';
    } else if (err?.responseCode >= 500) {
      detail = `The mail server rejected the message (${err.responseCode}). It was NOT delivered. Tell the visitor honestly.`;
    }
    return { ok: false, detail };
  }
}

