/**
 * HOT LEAD email for the demo agent — sent through the project's own cPanel
 * mailbox over SMTP.
 *
 * Why cPanel rather than a third-party API: conversingai.com's DNS already
 * authenticates mail sent this way. SPF covers the hosting through `+mx` and
 * `include:spf.web-hosting.com`, and cPanel publishes a DKIM key on the
 * `default` selector. So these messages are SPF- and DKIM-signed today,
 * which is better deliverability than any provider whose DKIM is unfinished.
 *
 * The prompt says: "Never claim the email was successfully sent unless the
 * email tool confirms successful delivery or submission." This module returns
 * an honest { ok, detail } and never pretends.
 *
 * Environment variables (Vercel → Settings → Environment Variables):
 *   SMTP_HOST        the mail server, e.g. premium59.web-hosting.com
 *   SMTP_SERVERNAME  optional. Hostname to validate the TLS certificate
 *                    against, when it differs from SMTP_HOST.
 *   SMTP_PORT        465 (implicit TLS) or 587 (STARTTLS). Default 465.
 *   SMTP_USER        the full mailbox address, e.g. demo@conversingai.com
 *   SMTP_PASS        that mailbox's password
 *   LEAD_EMAIL_FROM  optional. Defaults to SMTP_USER. Keep it on the same
 *                    domain or SPF/DKIM alignment breaks.
 *   LEAD_EMAIL_NAME  optional display name. Default "Conversing AI Demo".
 *   LEAD_EMAIL_BCC   optional. Copies every demo lead to your own inbox.
 */

import nodemailer from 'nodemailer';

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** Digits only, so wa.me gets a clean number. */
function waDigits(n) {
  return String(n || '').replace(/[^\d]/g, '');
}

function block(title, body) {
  if (!body) return '';
  return `
    <tr><td style="padding:18px 24px 0;">
      <h2 style="margin:0 0 8px;font:700 15px/1.3 Arial,Helvetica,sans-serif;color:#0f172a;">${esc(title)}</h2>
      <div style="font:400 14px/1.7 Arial,Helvetica,sans-serif;color:#334155;white-space:pre-wrap;">${esc(body)}</div>
    </td></tr>`;
}

